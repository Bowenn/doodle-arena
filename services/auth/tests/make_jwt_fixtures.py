"""Writes the shared JWT verification fixtures (ADR 0001) to fixtures/jwt/ at the repo root.

Every service that verifies access tokens runs every case in cases.json against jwks.json, so
the rules are the same in Python, Go and Java. Run it from services/auth:

    uv run python -m tests.make_jwt_fixtures

The keys are generated fresh on every run and never written, so the fixtures hold no private
key. Valid tokens expire in 2100 and the expired one in 2021, so the cases don't depend on the
current time; clock-skew edge cases stay in each language's own tests.
"""

import base64
import hashlib
import hmac
import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import jwt
from cryptography.hazmat.primitives import serialization

from app.tokens import ALGORITHM, AUDIENCE, SigningKey, jwks
from tests.conftest import new_rsa_pem

ISSUER = "http://localhost:8080/api/auth"
OUT = Path(__file__).resolve().parents[3] / "fixtures" / "jwt"

IAT = int(datetime(2026, 1, 1, tzinfo=UTC).timestamp())
EXP = int(datetime(2100, 1, 1, tzinfo=UTC).timestamp())


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def claims(**overrides: Any) -> dict[str, Any]:
    base: dict[str, Any] = {
        "sub": "u-fixture",
        "roles": ["player"],
        "iss": ISSUER,
        "aud": AUDIENCE,
        "iat": IAT,
        "exp": EXP,
        "jti": "fixture",
    }
    return {k: v for k, v in (base | overrides).items() if v is not None}


def sign(key: SigningKey, payload: dict[str, Any], kid: str | None = None) -> str:
    return jwt.encode(payload, key.private_key, ALGORITHM, headers={"kid": kid or key.kid})


def unsigned(alg: str, kid: str) -> str:
    header = b64url(json.dumps({"alg": alg, "kid": kid, "typ": "JWT"}).encode())
    return header + "." + b64url(json.dumps(claims()).encode())


def build() -> tuple[dict[str, Any], dict[str, Any]]:
    trusted = SigningKey.from_pem(new_rsa_pem())
    other = SigningKey.from_pem(new_rsa_pem())
    public_pem = trusted.public_key.public_bytes(
        serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo
    )
    hs256_input = unsigned("HS256", trusted.kid)
    hs256_sig = hmac.new(public_pem, hs256_input.encode(), hashlib.sha256).digest()

    def ok(name: str, token: str, roles: list[str]) -> dict[str, Any]:
        return {"name": name, "valid": True, "token": token, "sub": "u-fixture", "roles": roles}

    def bad(name: str, token: str, why: str) -> dict[str, Any]:
        return {"name": name, "valid": False, "token": token, "why": why}

    cases = [
        ok("valid", sign(trusted, claims()), ["player"]),
        ok(
            "valid_moderator",
            sign(trusted, claims(roles=["player", "moderator"])),
            ["player", "moderator"],
        ),
        bad(
            "expired",
            sign(trusted, claims(iat=IAT - 10**8, exp=IAT - 10**8 + 900)),
            "exp is in the past",
        ),
        bad("issued_in_future", sign(trusted, claims(iat=EXP - 60)), "iat is far in the future"),
        bad("missing_exp", sign(trusted, claims(exp=None)), "exp is required"),
        bad("missing_sub", sign(trusted, claims(sub=None)), "sub is required"),
        bad("wrong_audience", sign(trusted, claims(aud="other-api")), "aud must be doodle-api"),
        bad("wrong_issuer", sign(trusted, claims(iss="https://evil.example")), "iss must match"),
        bad(
            "roles_not_a_list",
            sign(trusted, claims(roles="admin")),
            "roles must be a list of strings",
        ),
        bad("unknown_kid", sign(other, claims()), "signed by a key that isn't in the JWKS"),
        bad(
            "forged_with_trusted_kid",
            sign(other, claims(), kid=trusted.kid),
            "signature doesn't match the key",
        ),
        bad("alg_none", unsigned("none", trusted.kid) + ".", "alg none is never accepted"),
        bad(
            "hs256_with_public_key", f"{hs256_input}.{b64url(hs256_sig)}", "only RS256 is accepted"
        ),
        bad("garbage", "not-a-jwt", "not a JWT"),
    ]
    doc = {
        "about": "Shared JWT verification cases (ADR 0001). Generated by "
        "services/auth/tests/make_jwt_fixtures.py; don't edit by hand.",
        "issuer": ISSUER,
        "audience": AUDIENCE,
        "cases": cases,
    }
    return jwks({trusted.kid: trusted.public_key}), doc


def main() -> None:
    key_set, doc = build()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "jwks.json").write_text(json.dumps(key_set, indent=2) + "\n")
    (OUT / "cases.json").write_text(json.dumps(doc, indent=2) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
